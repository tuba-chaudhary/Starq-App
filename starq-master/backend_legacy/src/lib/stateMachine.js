const STATUSES = [
  'DRAFT',
  'PENDING_PAYMENT',
  'PAYMENT_PROCESSING',
  'PAYMENT_FAILED',
  'CONFIRMED',
  'ASSIGNMENT_PENDING',
  'PARTNER_ASSIGNED',
  'PARTNER_ON_THE_WAY',
  'PARTNER_ARRIVED',
  'SERVICE_STARTED',
  'SERVICE_IN_PROGRESS',
  'SERVICE_COMPLETED',
  'CUSTOMER_FEEDBACK_PENDING',
  'COMPLETED',
  'CANCELLED',
  'REFUND_PENDING',
  'REFUNDED',
];

const TRANSITIONS = {
  DRAFT: ['PENDING_PAYMENT', 'CANCELLED'],
  PENDING_PAYMENT: ['PAYMENT_PROCESSING', 'CANCELLED', 'PAYMENT_FAILED'],
  PAYMENT_PROCESSING: ['CONFIRMED', 'PAYMENT_FAILED', 'CANCELLED'],
  PAYMENT_FAILED: ['PENDING_PAYMENT', 'CANCELLED'],
  CONFIRMED: ['ASSIGNMENT_PENDING', 'CANCELLED', 'REFUND_PENDING'],
  ASSIGNMENT_PENDING: ['PARTNER_ASSIGNED', 'CANCELLED'],
  PARTNER_ASSIGNED: ['PARTNER_ON_THE_WAY', 'ASSIGNMENT_PENDING', 'CANCELLED'],
  PARTNER_ON_THE_WAY: ['PARTNER_ARRIVED', 'CANCELLED'],
  PARTNER_ARRIVED: ['SERVICE_STARTED', 'CANCELLED'],
  SERVICE_STARTED: ['SERVICE_IN_PROGRESS', 'CANCELLED'],
  SERVICE_IN_PROGRESS: ['SERVICE_COMPLETED'],
  SERVICE_COMPLETED: ['CUSTOMER_FEEDBACK_PENDING', 'COMPLETED'],
  CUSTOMER_FEEDBACK_PENDING: ['COMPLETED'],
  COMPLETED: [],
  CANCELLED: ['REFUND_PENDING'],
  REFUND_PENDING: ['REFUNDED'],
  REFUNDED: [],
};

function assertTransition(from, to) {
  const allowed = TRANSITIONS[from] || [];
  if (!allowed.includes(to)) {
    const err = new Error(`Invalid booking status transition: ${from} → ${to}`);
    err.status = 422;
    throw err;
  }
}

function isTrackingActive(status) {
  return ['PARTNER_ASSIGNED', 'PARTNER_ON_THE_WAY', 'PARTNER_ARRIVED'].includes(status);
}

module.exports = { STATUSES, TRANSITIONS, assertTransition, isTrackingActive };
