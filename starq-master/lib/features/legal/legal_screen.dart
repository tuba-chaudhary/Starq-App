import 'package:flutter/material.dart';
import 'package:go_router/go_router.dart';
import 'package:starq_app/app/theme/app_theme.dart';

class LegalScreen extends StatelessWidget {
  final String title;
  
  const LegalScreen({super.key, required this.title});

  String _getContent() {
    if (title.contains('Terms')) {
      return "Terms & Conditions\n\n1. Service Scope and Eligibility\nSTARQ provides doorstep vehicle cleaning. You must be 18 to book.\n\n2. Pricing & Payments\nFinal price generated by backend. Paid securely via Razorpay.\n\n3. Liability\nSTARQ is not responsible for pre-existing damage. See full document in docs/legal/TERMS_AND_CONDITIONS.md.";
    } else if (title.contains('Privacy')) {
      return "Privacy Policy\n\nWe collect basic account information and active booking location (for partners). Payments are handled by Razorpay. We do not sell your data. See full document in docs/legal/PRIVACY_POLICY.md.";
    } else if (title.contains('Refund')) {
      return "Cancellation & Refund Policy\n\nCancel before partner assignment for no penalty. Once assigned, a fee may apply. Refunds process via Razorpay and may take 5-7 business days. See full document in docs/legal/CANCELLATION_REFUND_POLICY.md.";
    }
    return "Legal Document for $title";
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: Colors.white,
      appBar: AppBar(
        backgroundColor: AppColors.primary,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back, color: Colors.white),
          onPressed: () => context.pop(),
        ),
        title: Text(title, style: const TextStyle(color: Colors.white)),
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(20),
        child: Text(
          _getContent(),
          style: AppTextStyles.body.copyWith(height: 1.6),
        ),
      ),
    );
  }
}
